void zgui::sdl2_opengl::OpenGLGraphics::append_geometry(const zgui::Vertex* vertices,
                                                        std::size_t count) {
    if (count == 0)
        return;
    const bool disconnected_topology =
        pending_topology_ == zgui::VertexTopology::LINE_LIST ||
        pending_topology_ == zgui::VertexTopology::TRIANGLE_LIST;
    if (disconnected_topology && !batches_.empty() &&
        batches_.back().topology == pending_topology_) {
        batches_.back().vertices.insert(batches_.back().vertices.end(), vertices,
                                        vertices + count);
        return;
    }

    Batch batch;
    batch.topology = pending_topology_;
    batch.vertices.assign(vertices, vertices + count);
    batches_.push_back(std::move(batch));
}

void zgui::sdl2_opengl::OpenGLGraphics::flush_geometry() {
    if (batches_.empty())
        return;

    glDisable(GL_TEXTURE_2D);
    for (const Batch& batch : batches_) {
        glBegin(gl_topology(batch.topology));
        for (const Vertex& vertex : batch.vertices) {
            glColor4ub(vertex.color.r, vertex.color.g, vertex.color.b, vertex.color.a);
            glVertex2f(vertex.position.x, vertex.position.y);
        }
        glEnd();
    }
    batches_.clear();
}

void zgui::sdl2_opengl::OpenGLGraphics::draw() {
    flush_geometry();
}

void zgui::sdl2_opengl::OpenGLGraphics::reset() {
    batches_.clear();
    vertices_.clear();
}

void zgui::sdl2_opengl::OpenGLGraphics::set_clip_rect(int x, int y, int w, int h) {
    glEnable(GL_SCISSOR_TEST);
    const std::int64_t scissor_y =
        static_cast<std::int64_t>(viewport_height_) -
        (static_cast<std::int64_t>(y) + static_cast<std::int64_t>(h));
    const GLint bounded_y = static_cast<GLint>(
        std::clamp<std::int64_t>(scissor_y, std::numeric_limits<GLint>::min(),
                                 std::numeric_limits<GLint>::max()));
    glScissor(x, bounded_y, std::max(0, w), std::max(0, h));
}

void zgui::sdl2_opengl::OpenGLGraphics::reset_clip_rect() {
    glDisable(GL_SCISSOR_TEST);
}

void zgui::sdl2_opengl::OpenGLGraphics::initialize_font() {
    if (font_texture_ != 0)
        return;

    std::vector<GLubyte> pixels(static_cast<std::size_t>(kAtlasWidth * kAtlasHeight), 0);
    for (int top_y = 0; top_y < kAtlasHeight; ++top_y) {
        for (int x = 0; x < kAtlasWidth; ++x) {
            const std::size_t bit = static_cast<std::size_t>(top_y * kAtlasWidth + x);
            const std::uint8_t mask = static_cast<std::uint8_t>(1u << (7 - bit % 8));
            if ((kPackedFontAtlas[bit / 8] & mask) == 0)
                continue;
            const int gl_y = kAtlasHeight - 1 - top_y;
            pixels[static_cast<std::size_t>(gl_y * kAtlasWidth + x)] = 255;
        }
    }

    glGenTextures(1, &font_texture_);
    glBindTexture(GL_TEXTURE_2D, font_texture_);
    GLint previous_unpack_alignment = 4;
    glGetIntegerv(GL_UNPACK_ALIGNMENT, &previous_unpack_alignment);
    glPixelStorei(GL_UNPACK_ALIGNMENT, 1);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_NEAREST);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_NEAREST);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, GL_CLAMP_TO_EDGE);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_T, GL_CLAMP_TO_EDGE);
    glTexEnvi(GL_TEXTURE_ENV, GL_TEXTURE_ENV_MODE, GL_MODULATE);
    glTexImage2D(GL_TEXTURE_2D, 0, GL_ALPHA, kAtlasWidth, kAtlasHeight, 0, GL_ALPHA,
                 GL_UNSIGNED_BYTE, pixels.data());
    glPixelStorei(GL_UNPACK_ALIGNMENT, previous_unpack_alignment);
}

void zgui::sdl2_opengl::OpenGLGraphics::draw_text(const std::string& text, zgui::Point position,
                                                  zgui::Color color) {
    flush_geometry();
    initialize_font();
    glEnable(GL_TEXTURE_2D);
    glBindTexture(GL_TEXTURE_2D, font_texture_);
    const auto draw_pass = [&](float offset_x, float offset_y, zgui::Color pass_color) {
        float x = std::round(position.x) + offset_x;
        float y = std::round(position.y) + offset_y;
        glColor4ub(pass_color.r, pass_color.g, pass_color.b, pass_color.a);
        glBegin(GL_QUADS);
        unsigned char previous = 0;
        for (std::size_t index = 0; index < text.size();) {
            bool em_dash = false;
            const auto character = next_text_character(text, index, em_dash);
            if (character == '\n') {
                x = std::round(position.x) + offset_x;
                y += static_cast<float>(kCellHeight);
                previous = 0;
                continue;
            }
            if (previous != 0)
                x += static_cast<float>(pair_spacing_adjustment(previous, character));
            const int glyph = glyph_index(character);
            const GlyphMetrics metrics = glyph_metrics(character);
            if (metrics.width > 0) {
                const int cell_x = (glyph % kAtlasColumns) * kCellWidth;
                const int cell_y = (glyph / kAtlasColumns) * kCellHeight;
                const float u0 =
                    (static_cast<float>(cell_x + 1) + 0.5f) / static_cast<float>(kAtlasWidth);
                const float u1 = (static_cast<float>(cell_x + 1 + metrics.width) - 0.5f) /
                                 static_cast<float>(kAtlasWidth);
                const float v_top = 1.f - (static_cast<float>(cell_y + 1) + 0.5f) /
                                              static_cast<float>(kAtlasHeight);
                const float v_bottom =
                    1.f - (static_cast<float>(cell_y + 1 + kGlyphHeight) - 0.5f) /
                              static_cast<float>(kAtlasHeight);
                const float glyph_x = x + static_cast<float>(metrics.left);
                glTexCoord2f(u0, v_top);
                glVertex2f(glyph_x, y);
                glTexCoord2f(u1, v_top);
                glVertex2f(glyph_x + static_cast<float>(metrics.width) * (em_dash ? 2.f : 1.f), y);
                glTexCoord2f(u1, v_bottom);
                glVertex2f(glyph_x + static_cast<float>(metrics.width) * (em_dash ? 2.f : 1.f),
                           y + static_cast<float>(kGlyphHeight));
                glTexCoord2f(u0, v_bottom);
                glVertex2f(glyph_x, y + static_cast<float>(kGlyphHeight));
            }
            x += static_cast<float>(metrics.advance) * (em_dash ? 2.f : 1.f);
            previous = character;
        }
        glEnd();
    };

    const int brightness = 299 * static_cast<int>(color.r) + 587 * static_cast<int>(color.g) +
                           114 * static_cast<int>(color.b);
    const zgui::Color outline = brightness < 128000 ? zgui::Color(255, 255, 255)
                                                    : zgui::Color(0, 0, 0);
    for (const auto& offset : std::array<std::array<float, 2>, 8>{{{{-1.f, -1.f}},
                                                                   {{0.f, -1.f}},
                                                                   {{1.f, -1.f}},
                                                                   {{-1.f, 0.f}},
                                                                   {{1.f, 0.f}},
                                                                   {{-1.f, 1.f}},
                                                                   {{0.f, 1.f}},
                                                                   {{1.f, 1.f}}}})
        draw_pass(offset[0], offset[1], outline);
    draw_pass(0.f, 0.f, color);
}

float zgui::sdl2_opengl::OpenGLGraphics::measure_text_width(const std::string& text) const {
    float line_width = 0.f;
    float maximum_width = 0.f;
    unsigned char previous = 0;
    for (std::size_t index = 0; index < text.size();) {
        bool em_dash = false;
        const auto character = next_text_character(text, index, em_dash);
        if (character == '\n') {
            maximum_width = std::max(maximum_width, line_width);
            line_width = 0.f;
            previous = 0;
        } else {
            if (previous != 0)
                line_width += static_cast<float>(pair_spacing_adjustment(previous, character));
            line_width += static_cast<float>(glyph_metrics(character).advance) *
                          (em_dash ? 2.f : 1.f);
            previous = character;
        }
    }
    maximum_width = std::max(maximum_width, line_width);
    return maximum_width;
}

zgui::sdl2_opengl::SDL2Input::SDL2Input() {
    int x = 0;
    int y = 0;
    const Uint32 state = SDL_GetMouseState(&x, &y);
    mouse_position_ = Point(static_cast<float>(x), static_cast<float>(y));
    left_button_pressed_ = (state & SDL_BUTTON(SDL_BUTTON_LEFT)) != 0;
}

void zgui::sdl2_opengl::SDL2Input::begin_frame() {
    mouse_wheel_delta_ = 0;
    mouse_delta_ = Point(0.f, 0.f);
    mouse_double_clicked_ = false;
    escape_pressed_ = false;
}

void zgui::sdl2_opengl::SDL2Input::process_event(const SDL_Event& event) {
    switch (event.type) {
    case SDL_MOUSEMOTION:
        mouse_delta_.x += static_cast<float>(event.motion.xrel);
        mouse_delta_.y += static_cast<float>(event.motion.yrel);
        mouse_position_ =
            Point(static_cast<float>(event.motion.x), static_cast<float>(event.motion.y));
        break;
    case SDL_MOUSEBUTTONDOWN:
    case SDL_MOUSEBUTTONUP:
        mouse_position_ =
            Point(static_cast<float>(event.button.x), static_cast<float>(event.button.y));
        if (event.type == SDL_MOUSEBUTTONDOWN) {
            pressed_keys_.push_back(-static_cast<int>(event.button.button));
            if (event.button.button == SDL_BUTTON_LEFT) {
                const Uint32 now = SDL_GetTicks();
                const float dx = mouse_position_.x - last_click_position_.x;
                const float dy = mouse_position_.y - last_click_position_.y;
                mouse_double_clicked_ = have_last_click_ &&
                                        static_cast<Uint32>(now - last_click_time_) <= 350u &&
                                        dx * dx + dy * dy <= 25.f;
                last_click_time_ = now;
                last_click_position_ = mouse_position_;
                have_last_click_ = true;
            }
        }
        if (event.button.button == SDL_BUTTON_LEFT)
            left_button_pressed_ = event.type == SDL_MOUSEBUTTONDOWN;
        else if (event.button.button == SDL_BUTTON_MIDDLE)
            middle_button_pressed_ = event.type == SDL_MOUSEBUTTONDOWN;
        else if (event.button.button == SDL_BUTTON_RIGHT)
            right_button_pressed_ = event.type == SDL_MOUSEBUTTONDOWN;
        break;
    case SDL_MOUSEWHEEL: {
        const int delta =
            event.wheel.direction == SDL_MOUSEWHEEL_FLIPPED ? -event.wheel.y : event.wheel.y;
        mouse_wheel_delta_ += delta;
        break;
    }
    case SDL_KEYDOWN: {
        const int key = static_cast<int>(event.key.keysym.sym);
        if (event.key.repeat == 0) {
            keys_down_.insert(key);
            pressed_keys_.push_back(key);
            if (event.key.keysym.sym == SDLK_ESCAPE)
                escape_pressed_ = true;
        }
        if (event.key.keysym.sym == SDLK_BACKSPACE)
            text_input_.push_back('\b');
        else if (event.key.keysym.sym == SDLK_RETURN || event.key.keysym.sym == SDLK_KP_ENTER)
            text_input_.push_back('\n');
        else if (event.key.keysym.sym == SDLK_ESCAPE)
            text_input_.push_back('\x1b');
        break;
    }
    case SDL_KEYUP:
        keys_down_.erase(static_cast<int>(event.key.keysym.sym));
        break;
    case SDL_TEXTINPUT:
        for (const char* character = event.text.text; *character != '\0'; ++character)
            text_input_.push_back(*character);
        break;
    case SDL_WINDOWEVENT:
        if (event.window.event == SDL_WINDOWEVENT_FOCUS_LOST) {
            left_button_pressed_ = false;
            middle_button_pressed_ = false;
            right_button_pressed_ = false;
            keys_down_.clear();
            text_input_.clear();
            pressed_keys_.clear();
            zgui::core::focused_text_input = nullptr;
        }
        break;
    default:
        break;
    }
}

bool zgui::sdl2_opengl::SDL2Input::key_pressed(int key) const {
    return keys_down_.find(key) != keys_down_.end();
}

