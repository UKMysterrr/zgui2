bool zgui::sdl2_opengl::SDL2Input::pop_text_input(char& character) {
    if (text_input_.empty())
        return false;
    character = text_input_.front();
    text_input_.pop_front();
    return true;
}

std::optional<int> zgui::sdl2_opengl::SDL2Input::poll_pressed_key() {
    if (pressed_keys_.empty())
        return std::nullopt;
    const int key = pressed_keys_.front();
    pressed_keys_.pop_front();
    return key;
}

std::string zgui::sdl2_opengl::SDL2Input::key_name(int key) const {
    if (key == 0)
        return "None";
    if (key < 0) {
        const int button = -key;
        if (button == SDL_BUTTON_X1)
            return "Mouse4";
        if (button == SDL_BUTTON_X2)
            return "Mouse5";
        return "Mouse" + std::to_string(button);
    }

    switch (key) {
    case SDLK_LSHIFT:
    case SDLK_RSHIFT:
        return "Shift";
    case SDLK_LCTRL:
    case SDLK_RCTRL:
        return "Ctrl";
    case SDLK_LALT:
        return "LMENU";
    case SDLK_RALT:
        return "Alt";
    case SDLK_LGUI:
    case SDLK_RGUI:
        return "Super";
    default:
        break;
    }

    const char* name = SDL_GetKeyName(static_cast<SDL_Keycode>(key));
    return name == nullptr || *name == '\0' ? "Unknown" : name;
}

int zgui::sdl2_opengl::run_sdl2_opengl_application(const std::string& title, int width, int height,
                                                   const ApplicationSetup& setup,
                                                   std::size_t frame_limit,
                                                   const ApplicationFrame& on_frame) {
    if (width <= 0 || height <= 0 || !setup) {
        std::cerr << "invalid SDL2/OpenGL application configuration\n";
        return 1;
    }
    SDLRuntime runtime;
    if (SDL_Init(SDL_INIT_VIDEO) != 0) {
        std::cerr << "SDL_Init failed: " << SDL_GetError() << '\n';
        return 1;
    }
    runtime.initialized = true;

    SDL_GL_SetAttribute(SDL_GL_CONTEXT_MAJOR_VERSION, 2);
    SDL_GL_SetAttribute(SDL_GL_CONTEXT_MINOR_VERSION, 1);
    SDL_GL_SetAttribute(SDL_GL_DOUBLEBUFFER, 1);
    SDL_GL_SetAttribute(SDL_GL_DEPTH_SIZE, 24);
    runtime.window =
        SDL_CreateWindow(title.c_str(), SDL_WINDOWPOS_CENTERED, SDL_WINDOWPOS_CENTERED, width,
                         height, SDL_WINDOW_OPENGL | SDL_WINDOW_RESIZABLE);
    if (runtime.window == nullptr) {
        std::cerr << "SDL_CreateWindow failed: " << SDL_GetError() << '\n';
        return 1;
    }

    runtime.context = SDL_GL_CreateContext(runtime.window);
    if (runtime.context == nullptr) {
        std::cerr << "SDL_GL_CreateContext failed: " << SDL_GetError() << '\n';
        return 1;
    }
    if (SDL_GL_MakeCurrent(runtime.window, runtime.context) != 0) {
        std::cerr << "SDL_GL_MakeCurrent failed: " << SDL_GetError() << '\n';
        return 1;
    }

    int result = 0;
    SDL_GL_SetSwapInterval(1);
    SDL_StartTextInput();
    runtime.text_input_started = true;
    {
        auto graphics = std::make_shared<OpenGLGraphics>();
        auto input = std::make_shared<SDL2Input>();
        zgui::core::graphics = graphics;
        zgui::core::input = input;
        {
            WindowManager manager;
            zgui::core::window_manager = &manager;
            try {
                setup(manager, *graphics);
                bool running = true;
                std::size_t frame_index = 0;
                while (running) {
                    input->begin_frame();
                    SDL_Event event;
                    while (SDL_PollEvent(&event) != 0) {
                        input->process_event(event);
                        if (event.type == SDL_QUIT ||
                            (event.type == SDL_KEYDOWN && event.key.keysym.sym == SDLK_ESCAPE))
                            running = false;
                    }

                    int viewport_width = 0;
                    int viewport_height = 0;
                    SDL_GL_GetDrawableSize(runtime.window, &viewport_width, &viewport_height);
                    if (viewport_width <= 0 || viewport_height <= 0) {
                        SDL_Delay(8);
                        continue;
                    }

                    glViewport(0, 0, viewport_width, viewport_height);
                    glClearColor(0.18f, 0.22f, 0.28f, 1.f);
                    glClear(GL_COLOR_BUFFER_BIT | GL_DEPTH_BUFFER_BIT);
                    graphics->begin_frame(viewport_width, viewport_height);
                    if (on_frame)
                        on_frame(manager, *graphics, *input, frame_index);
                    manager.update();
                    manager.draw();
                    graphics->end_frame();
                    SDL_GL_SwapWindow(runtime.window);
                    ++frame_index;
                    if (frame_limit > 0 && frame_index >= frame_limit)
                        running = false;
                }
            } catch (const std::exception& error) {
                std::cerr << "SDL application failed: " << error.what() << '\n';
                result = 1;
            }
        }
        graphics->release_resources();
        zgui::core::focused_text_input = nullptr;
        zgui::core::window_manager = nullptr;
        zgui::core::graphics.reset();
        zgui::core::input.reset();
    }
    return result;
}

int zgui::sdl2_opengl::run_sdl2_opengl_application(const std::string& title, int width, int height,
                                                   const ApplicationSetup& setup) {
    return run_sdl2_opengl_application(title, width, height, setup, 0, {});
}
