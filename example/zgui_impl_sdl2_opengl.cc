void zgui::sdl2_opengl::OpenGLGraphics::begin_frame(int viewport_width, int viewport_height) {
    if (frame_active_)
        throw std::logic_error("OpenGLGraphics frame is already active");
    if (viewport_width <= 0 || viewport_height <= 0)
        throw std::invalid_argument("OpenGL viewport dimensions must be positive");

    if (use_program_ == nullptr) {
        use_program_ = reinterpret_cast<UseProgramProc>(SDL_GL_GetProcAddress("glUseProgram"));
        if (use_program_ == nullptr)
            throw std::runtime_error("OpenGL 2.0 glUseProgram is unavailable");
    }

    reset();
    viewport_width_ = viewport_width;
    viewport_height_ = viewport_height;
    glGetIntegerv(GL_MATRIX_MODE, &previous_matrix_mode_);
    glGetIntegerv(kCurrentProgram, &previous_program_);
    glPushAttrib(GL_ALL_ATTRIB_BITS);

    use_program_(0);
    glDisable(GL_SCISSOR_TEST);
    glDisable(GL_DEPTH_TEST);
    glDisable(GL_STENCIL_TEST);
    glDisable(GL_CULL_FACE);
    glDisable(GL_LIGHTING);
    glShadeModel(GL_SMOOTH);
    glEnable(GL_BLEND);
    glBlendFunc(GL_SRC_ALPHA, GL_ONE_MINUS_SRC_ALPHA);

    glMatrixMode(GL_PROJECTION);
    glPushMatrix();
    glLoadIdentity();
    glOrtho(0.0, static_cast<GLdouble>(viewport_width_), static_cast<GLdouble>(viewport_height_),
            0.0, -1.0, 1.0);
    glMatrixMode(GL_MODELVIEW);
    glPushMatrix();
    glLoadIdentity();
    frame_active_ = true;
}

void zgui::sdl2_opengl::OpenGLGraphics::end_frame() {
    if (!frame_active_)
        throw std::logic_error("OpenGLGraphics has no active frame");

    draw();
    glMatrixMode(GL_MODELVIEW);
    glPopMatrix();
    glMatrixMode(GL_PROJECTION);
    glPopMatrix();
    glMatrixMode(static_cast<GLenum>(previous_matrix_mode_));
    glPopAttrib();
    use_program_(static_cast<GLuint>(previous_program_));
    frame_active_ = false;
}

void zgui::sdl2_opengl::OpenGLGraphics::release_font_texture() {
    if (font_texture_ != 0) {
        glDeleteTextures(1, &font_texture_);
        font_texture_ = 0;
    }
}

void zgui::sdl2_opengl::OpenGLGraphics::release_resources() {
    release_font_texture();
}

bool zgui::sdl2_opengl::OpenGLGraphics::font_spacing_valid(std::string* error) const {
    constexpr std::string_view characters =
        "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789";
    for (char previous_char : characters) {
        const auto previous = static_cast<unsigned char>(previous_char);
        for (char current_char : characters) {
            const auto current = static_cast<unsigned char>(current_char);
            const GlyphMetrics left = glyph_metrics(previous);
            const GlyphMetrics right = glyph_metrics(current);
            const int gap = left.advance + pair_spacing_adjustment(previous, current) + right.left -
                            left.left - left.width;
            if (gap < 1 || gap > 3) {
                if (error != nullptr)
                    *error = std::string("invalid glyph gap for ") + static_cast<char>(previous) +
                             static_cast<char>(current) + ": " + std::to_string(gap);
                return false;
            }
        }
    }
    if (error != nullptr)
        error->clear();
    return true;
}

