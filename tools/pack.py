#!/usr/bin/env python3
"""Generate the distributable two-file zgui package from its canonical sources."""

import re
import subprocess
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE_DIR = ROOT
OUTPUT_DIR = ROOT / "dist"


def version_string() -> str:
    header = (SOURCE_DIR / "zgui.hh").read_text(encoding="utf-8")
    match = re.search(r'^#define ZGUI_VERSION_STRING "([^"]+)"$', header, re.MULTILINE)
    if match is None:
        raise RuntimeError("ZGUI_VERSION_STRING is missing from zgui.hh")
    return match.group(1)


def git_describe() -> str:
    try:
        result = subprocess.run(
            ["git", "describe", "--tags", "--always", "--dirty"],
            cwd=ROOT,
            check=False,
            capture_output=True,
            text=True,
        )
    except FileNotFoundError:
        return "unavailable"
    if result.returncode == 0 and result.stdout.strip():
        return result.stdout.strip()
    return "unavailable"


def add_build_stamp(source: str, filename: str, version: str, revision: str) -> str:
    lines = source.splitlines(keepends=True)
    for index, line in enumerate(lines):
        if "SPDX-License-Identifier: MIT" in line:
            lines.insert(
                index + 1,
                f"// Generated by tools/pack.py; zgui {version} ({revision}).\n",
            )
            return "".join(lines)
    raise RuntimeError(f"{filename} is missing its MIT SPDX license header")


def main() -> None:
    version = version_string()
    revision = git_describe()
    OUTPUT_DIR.mkdir(exist_ok=True)

    for filename in ("zgui.hh", "zgui.cc"):
        source = (SOURCE_DIR / filename).read_text(encoding="utf-8")
        packed = add_build_stamp(source, filename, version, revision)
        (OUTPUT_DIR / filename).write_text(packed, encoding="utf-8")

    print(f"Packed zgui {version} ({revision}) into {OUTPUT_DIR}")


if __name__ == "__main__":
    main()
